// Named combos reward owning companies that are tied together in the real world:
// partnerships, supply chains, rivalries that together dominate a market, or shared owners.
// A combo activates when you own at least `need` of its members (and its anchor, if any).
// The bonus is added to the turnover of every member you own.

export interface ComboTier {
  need: number;
  bonus: number;
}

export interface ComboDef {
  id: string;
  name: string;
  icon: string;
  members: string[];
  /** If set, this company must be one of the owned members for the combo to count. */
  anchor?: string;
  tiers: ComboTier[];
  why: string;
}

const t = (...pairs: [number, number][]): ComboTier[] =>
  pairs.map(([need, bonus]) => ({ need, bonus }));

